function normalizeTensorInPlace(v, out) {
    let sum = 0;
    for (let i = 0; i < v.length; i++) sum += v[i] * v[i];
    let mag = Math.sqrt(sum) || 1e-8;
    for (let i = 0; i < v.length; i++) out[i] = v[i] / mag;
}

function contractToUnisphereInPlace(x, y, z, out) {
    let mag = Math.hypot(x, y, z);
    if (mag > 1.0) {
        if (mag === Infinity) {
            x = 0; y = 0; z = 0; // Prevent Infinity * 0 = NaN
        } else {
            let scale = (2.0 - 1.0 / mag) / mag;
            x *= scale;
            y *= scale;
            z *= scale;
        }
    }
    out[0] = x / 4.0 + 0.5;
    out[1] = y / 4.0 + 0.5;
    out[2] = z / 4.0 + 0.5;
}



    function halfToFloat(h) {
        let s = (h & 0x8000) >> 15;
        let e = (h & 0x7C00) >> 10;
        let f = h & 0x03FF;
        if(e === 0) return (s ? -1 : 1) * Math.pow(2, -14) * (f / 1024);
        if(e === 0x1F) return f ? NaN : ((s ? -1 : 1) * Infinity);
        return (s ? -1 : 1) * Math.pow(2, e - 15) * (1 + f / 1024);
    }

    // Expands a 10-bit integer into 30 bits for Morton encoding
    function expandBits(v) {
        v = (v | (v << 16)) & 0x030000ff;
        v = (v | (v <<  8)) & 0x0300f00f;
        v = (v | (v <<  4)) & 0x030c30c3;
        v = (v | (v <<  2)) & 0x09249249;
        return v;
    }

    // Calculates a 3D Morton code from 16-bit inputs (scaled down to 10-bit to fit in 32-bit int)
    function calculateMortonCode(x, y, z) {
        let xx = Math.floor((x / 65535.0) * 1023.0);
        let yy = Math.floor((y / 65535.0) * 1023.0);
        let zz = Math.floor((z / 65535.0) * 1023.0);
        return (expandBits(xx) | (expandBits(yy) << 1) | (expandBits(zz) << 2));
    }

    function floatToHalf(float) {
        _floatView[0] = float;
        var f = _int32View[0];

        var sign = (f >> 31) & 0x0001;
        var exp = (f >> 23) & 0x00ff;
        var frac = f & 0x007fffff;

        var newExp;
        if (exp == 0) {
            newExp = 0;
        } else if (exp < 113) {
            newExp = 0;
            frac |= 0x00800000;
            frac = frac >> (113 - exp);
            if (frac & 0x01000000) {
                newExp = 1;
                frac = 0;
            }
        } else if (exp < 142) {
            newExp = exp - 112;
        } else {
            newExp = 31;
            frac = 0;
        }

        return (sign << 15) | (newExp << 10) | (frac >> 13);
    }

    function packHalf2x16(x, y) {
        return (floatToHalf(x) | (floatToHalf(y) << 16)) >>> 0;
    }

