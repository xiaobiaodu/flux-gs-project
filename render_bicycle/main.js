    // --- 1. HIGH-PERFORMANCE ZERO-ALLOCATION HELPERS ---
    const tcnn_current = new Float32Array(128);
    const tcnn_next = new Float32Array(128);

    function getTCNNFrequencyEncoding(x, y, z, num_freqs, outBuffer) {
        let idx = 0;
        const coords = [x, y, z];


        for (let i = 0; i < 3; i++) {
            let val = coords[i];
            for (let freq = 0; freq < num_freqs; freq++) {
                // 2. CRITICAL: Equivalent to C++ scalbnf(val, log2_frequency) * PI
                let input_val = val * Math.pow(2.0, freq) * Math.PI;

                outBuffer[idx++] = Math.sin(input_val);
                outBuffer[idx++] = Math.cos(input_val); 
            }
        }
        
        const fan_out_encoded = 3 * num_freqs * 2;
        const padded_size = Math.ceil(fan_out_encoded / 16) * 16;
        while (idx < padded_size) {
            outBuffer[idx++] = 1.0;
        }
    }
    function runTCNN_MLP(inputVector, flatParams, inDim, hiddenDim, outDim, numHiddenLayers, activation, outBuffer) {
    const pad16 = (val) => Math.ceil(val / 16) * 16;
    const paddedIn = pad16(inDim);
    const paddedHidden = pad16(hiddenDim);
    const paddedOut = pad16(outDim);
    
    tcnn_current.fill(0);
    tcnn_current.set(inputVector); 
    let offset = 0;

    const applyActivation = (val) => {
        if (activation === 'ReLU') return Math.max(0, val);
        if (activation === 'LeakyReLU') return val > 0 ? val : val * 0.01;
        return val;
    };

    for (let out_idx = 0; out_idx < paddedHidden; out_idx++) {
        let sum = 0;
        for (let in_idx = 0; in_idx < paddedIn; in_idx++) {
            sum += tcnn_current[in_idx] * flatParams[offset + out_idx * paddedIn + in_idx];
        }
        tcnn_next[out_idx] = applyActivation(sum);
    }
    offset += paddedIn * paddedHidden;
    
    // --- HIDDEN LAYERS ---
    for (let layer = 1; layer < numHiddenLayers; layer++) {
        tcnn_current.set(tcnn_next);
        for (let out_idx = 0; out_idx < paddedHidden; out_idx++) {
            let sum = 0;
            for (let in_idx = 0; in_idx < paddedHidden; in_idx++) {
                sum += tcnn_current[in_idx] * flatParams[offset + out_idx * paddedHidden + in_idx];
            }
            tcnn_next[out_idx] = applyActivation(sum);
        }
        offset += paddedHidden * paddedHidden;
    }
    
    // --- OUTPUT LAYER ---
    tcnn_current.set(tcnn_next);
    for (let out_idx = 0; out_idx < paddedOut; out_idx++) {
        let sum = 0;
        for (let in_idx = 0; in_idx < paddedHidden; in_idx++) {
            sum += tcnn_current[in_idx] * flatParams[offset + out_idx * paddedHidden + in_idx];
        }
        tcnn_next[out_idx] = sum; 
    }
    outBuffer.set(tcnn_next.subarray(0, outDim));
}





    function runPyTorch_MLP(inputVector, weights, biases, applyRelu, outBuffer) {
        let outDim = biases.length;
        let inDim = inputVector.length;
        for (let i = 0; i < outDim; i++) {
            let sum = biases[i];
            for (let j = 0; j < inDim; j++) sum += inputVector[j] * weights[i * inDim + j]; 
            outBuffer[i] = applyRelu ? Math.max(0, sum) : sum;
        }
    }

